KNET = []          # K-NET / KiK-net 真实观测点，由 load_knet() 填充


def load_knet(path):
    """读 data/knet_stations.json（NIED 官方台站名册），返回加进来的个数"""
    try:
        with open(path, "r", encoding="utf-8") as f:
            rows = json.load(f).get("stations") or []
    except Exception:
        return 0
    del KNET[:]
    for r in rows:
        if len(r) < 6:
            continue
        KNET.append({
            "code": r[0], "name": r[1], "country": "JP", "region": r[2],
            "lat": r[3], "lon": r[4], "net": r[5],
            "major": False, "custom": False,
        })
    return len(KNET)


